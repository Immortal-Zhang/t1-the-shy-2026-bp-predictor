"""Download official reference snapshots and reconcile event teams to real data.

Run from the repository root with `.venv/bin/python scripts/update_catalog.py`.
No new match, roster, prediction or result is generated by this script.
"""
from datetime import datetime, timezone
import hashlib
import html
import json
from pathlib import Path
import re

import pandas as pd
import requests

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data/catalog"
OUT.mkdir(parents=True, exist_ok=True)
SOURCES = {
    "champion-en_US.json": "https://ddragon.leagueoflegends.com/cdn/16.20.1/data/en_US/champion.json",
    "champion-zh_CN.json": "https://ddragon.leagueoflegends.com/cdn/16.20.1/data/zh_CN/champion.json",
    "worlds-2026-primer.html": "https://lolesports.com/en-GB/news/worlds-2026-primer",
    "riot-rules-library.html": "https://competitiveops.riotgames.com/en-US/library?game=lol",
    "worlds-2026-rules.pdf": "https://cdn.sanity.io/files/dsfx7636/news_live/faa5ce974e58615911fbee931c6123e2785a8b46.pdf",
    "international-2026-rules.pdf": "https://cdn.sanity.io/files/dsfx7636/news_live/d29e446e0a0d0813a8caaae1d2817dd82cfe79c6.pdf",
    "fearless-definition.html": "https://lolesports.com/en-US/news/lol-esports-in-2025",
    "riot-developer-policy.html": "https://developer.riotgames.com/policies/general",
}


def dump(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False) + "\n")


def main():
    retrieved = datetime.now(timezone.utc).isoformat()
    sources = []
    for filename, url in SOURCES.items():
        response = requests.get(url, timeout=40)
        response.raise_for_status()
        if filename.endswith(".json"):
            response.json()
        if filename.endswith(".pdf") and not response.content.startswith(b"%PDF"):
            raise ValueError(f"Invalid PDF response: {url}")
        (OUT / filename).write_bytes(response.content)
        sources.append({"filename": filename, "url": url, "retrieved_at": retrieved,
                        "sha256": hashlib.sha256(response.content).hexdigest(), "bytes": len(response.content)})

    source_text = (OUT / "worlds-2026-primer.html").read_text()
    source_text = source_text.replace(r"\u003c", "<").replace(r"\u003e", ">").replace(r"\u0026", "&")
    start = source_text.index("QUALIFIED TEAMS")
    end = source_text.index("WORLDS 2026 FORMAT", start)
    lines = [html.unescape(re.sub("<[^>]+>", "", part)).strip() for part in re.findall(r"<p>(.*?)</p>", source_text[start:end], flags=re.S)]
    observations = pd.read_parquet(ROOT / "data/processed/games.parquet")
    team_table = pd.concat([observations[[f"{side}_team_id", f"{side}_team_name"]].rename(
        columns={f"{side}_team_id": "team_id", f"{side}_team_name": "name"}) for side in ("blue", "red")]).drop_duplicates()
    # Explicit sponsor/typography correspondences reviewed against the provider's
    # displayed team names; never a fuzzy automated identity join.
    provider_names = {"Anyone’s Legend": "Anyone's Legend", "TOP Esports": "Top Esports",
                      "Shanghai Invictus Gaming Meituan": "Invictus Gaming", "Team Liquid Alienware": "Team Liquid",
                      "Cloud9 Kia": "Cloud9", "LOS": "LØS"}
    teams, region = [], None
    for line in lines:
        for candidate in ("LPL", "LCK", "LEC", "LCS", "LCP", "CBLOL"):
            if line.endswith(candidate) and "(" not in line:
                region = candidate
        found = re.fullmatch(r"(.+?)\s*\(([A-Z0-9]+)\)", line)
        if not found:
            continue
        name, code = found.groups()
        provider_name = provider_names.get(name, name)
        ids = team_table.loc[team_table.name.eq(provider_name), "team_id"].unique()
        if len(ids) != 1:
            raise ValueError(f"Team needs manual exact ID reconciliation: {name}: {list(ids)}")
        teams.append({"name": name, "code": code, "region": region, "team_id": str(ids[0]),
                      "provider_name": provider_name, "mapping_basis": "reviewed_exact_source_name_correspondence",
                      "participation_status": "official_confirmed", "source_url": SOURCES["worlds-2026-primer.html"],
                      "logo_url": None, "logo_license_status": "no_verified_reusable_team_logo_source"})
    if len(teams) != 19 or len({t["team_id"] for t in teams}) != 19:
        raise ValueError(f"Unexpected current official participant roster size: {len(teams)}")
    published_days = re.findall(r'<time\s+dateTime="(\d{4}-\d{2}-\d{2})"', source_text)
    if len(set(published_days)) != 1:
        raise ValueError("Official participant page publication day is missing or ambiguous")
    published_day = published_days[0]
    qualification_available_at = (pd.Timestamp(published_day, tz="UTC") + pd.Timedelta(days=1)).isoformat()
    participants = {"event": "Worlds 2026", "source_url": SOURCES["worlds-2026-primer.html"],
                    "source_published_date": published_day, "source_published_at": None,
                    "qualification_available_at": qualification_available_at,
                    "publication_time_basis": "Only a date is published in the source time element; use next UTC midnight and require strictly before as_of. Current snapshot may contain later edits.",
                    "retrieved_at": retrieved,
                    "notice": "Official team participation snapshot; does not assert current per-game starting rosters.", "teams": teams}
    dump(ROOT / "configs/worlds2026_participants.json", participants)

    rules = {"verified": True, "mechanism_verified": True, "fearless_mode": "global",
             "source_url": SOURCES["international-2026-rules.pdf"], "updated_at": retrieved,
             "definition_source_url": SOURCES["fearless-definition.html"],
             "event_source_url": SOURCES["worlds-2026-rules.pdf"],
             "description": "全局无畏征召：同一系列赛内，双方之前小局已经选用的英雄都不能再选；普通禁用不跨局累积。",
             "evidence_scope": "2026国际赛事规则4.5.6–4.5.7承认无畏模式并规定错误选禁处理；双方历史选用均不可复用的机制来自Riot官方Fearless解释。2026世界赛规则引用该国际赛事规则并给出Bo3/Bo5赛制。",
             "applicability_notice": "本工具管理用户指定的同一Bo3/Bo5无畏系列赛上下文；赛事特殊禁用、临时规则和实际名单仍以裁判公布为准。不要把不同系列赛的选用记录合并。",
             "formats": ["bo3", "bo5"], "series_prediction_supported": False,
             "previous_picks_restricted_for": "both_teams", "standard_bans_carry_over": False,
             "event_rules_sections": ["Worlds 2026 §1.1", "Worlds 2026 §§4.1.1–4.1.3", "International 2026 §§4.5.6–4.5.7"]}
    dump(OUT / "worlds_rules.json", rules)
    manifest = {"retrieved_at": retrieved, "champion_version": "16.20.1", "public_patch": "26.20",
                "champion_count": len(json.loads((OUT / "champion-en_US.json").read_text())["data"]),
                "champion_assets_source": "https://developer.riotgames.com/docs/lol#data-dragon",
                "policy_url": SOURCES["riot-developer-policy.html"],
                "champion_asset_terms": "Riot Data Dragon assets permitted by Riot developer policies; retain attribution and non-endorsement notice. Public products require Riot registration/review; this project is local-only.",
                "team_logo_policy": "No verified reusable team logos are bundled; neutral initials are not team marks.",
                "non_endorsement": "Worlds 2026 BP Predictor isn't endorsed by Riot Games and doesn't reflect the views or opinions of Riot Games or anyone officially involved in producing or managing Riot Games properties. Riot Games, and all associated properties are trademarks or registered trademarks of Riot Games, Inc.",
                "match_data_source": "https://chaincc.lol/free/data/", "match_data_license": "CC BY 4.0; attribution required",
                "sources": sources}
    dump(OUT / "manifest.json", manifest)
    dump(ROOT / "reports/phase2/catalog_sources.json", {"manifest": manifest, "participants": participants, "rules": rules,
         "roster_limitation": "No official per-game starter feed imported. Every auto-filled roster is a dated, source-observed lineup and must be confirmed by the user."})
    print(json.dumps({"champions": manifest["champion_count"], "verified_participating_teams": len(teams), "rules_verified": rules["verified"]}))


if __name__ == "__main__":
    main()
